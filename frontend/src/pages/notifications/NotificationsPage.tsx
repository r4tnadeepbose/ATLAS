import { useState } from "react";
import { useMutation, useQuery } from "@tanstack/react-query";
import { Bell, CheckCheck, Send } from "lucide-react";
import { notificationApi } from "@/api/endpoints";
import { useListQuery } from "@/hooks/useListQuery";
import { useAuth } from "@/context/AuthContext";
import { PageHeader } from "@/components/common/PageHeader";
import { Badge, Button, Card, CardHeader, EmptyState, Field, Input, Modal, Pagination, Select, SeverityBadge, Switch, Textarea, useToast } from "@/components/ui/primitives";
import { formatDateTime, relativeTime, titleCase } from "@/utils";
import type { Notification } from "@/types";

const EVENTS = ["vulnerable_dependency", "new_asset", "sensitive_data", "api_security", "posture_change", "remediation_deadline", "assessment_completed", "test"];

export function NotificationsPage() {
  const toast = useToast();
  const { can } = useAuth();
  const [unreadOnly, setUnreadOnly] = useState(false);
  const [severity, setSeverity] = useState("");
  const [ruleOpen, setRuleOpen] = useState(false);
  const [rule, setRule] = useState({ name: "", event_key: "vulnerable_dependency", min_severity: "high", channels: "in_app", dedup_window_minutes: 30 });

  const list = useListQuery<Notification>(["notifications"], notificationApi.list, { initialSort: "created_at", filters: { unread_only: unreadOnly || undefined, severity: severity || undefined } });
  const rules = useQuery({ queryKey: ["notification-rules"], queryFn: notificationApi.rules });

  const createRule = useMutation({
    mutationFn: () => notificationApi.createRule({ name: rule.name, event_key: rule.event_key, min_severity: rule.min_severity, channels: rule.channels.split(",").map((channel) => channel.trim()).filter(Boolean), dedup_window_minutes: Number(rule.dedup_window_minutes) }),
    onSuccess: () => {
      toast.push({ title: "Alert rule created", tone: "success" });
      setRuleOpen(false);
      rules.refetch();
    },
    onError: (error: Error) => toast.push({ title: "Rule failed", description: error.message, tone: "error" }),
  });

  return (
    <div className="space-y-4">
      <PageHeader
        eyebrow="Security Operations"
        title="Notification Center"
        description="Severity-based alerting with deduplication, delivery state and configurable routing."
        actions={
          can("notifications:write") ? (
            <>
              <Button variant="ghost" size="sm" onClick={async () => { await notificationApi.markAll(); toast.push({ title: "All notifications marked read", tone: "info" }); list.refetch(); }}>
                <CheckCheck className="h-3.5 w-3.5" /> Mark all read
              </Button>
              <Button variant="primary" size="sm" onClick={async () => { await notificationApi.test(); toast.push({ title: "Test notification delivered", tone: "success" }); list.refetch(); }}>
                <Send className="h-3.5 w-3.5" /> Send test
              </Button>
            </>
          ) : undefined
        }
      />

      <div className="grid grid-cols-1 gap-4 xl:grid-cols-3">
        <Card className="xl:col-span-2">
          <CardHeader
            title="Notification feed"
            description="In-app alerts and external delivery status"
            action={
              <div className="flex items-center gap-2">
                <Select value={severity} onChange={(event) => setSeverity(event.target.value)} className="h-8 w-[120px] text-xs">
                  <option value="">All severity</option>
                  {["critical", "high", "medium", "low", "info"].map((value) => <option key={value} value={value}>{titleCase(value)}</option>)}
                </Select>
                <Switch checked={unreadOnly} onChange={setUnreadOnly} label="Unread" />
              </div>
            }
          />
          {list.isLoading ? <div className="space-y-2 p-3">{Array.from({ length: 5 }).map((_, index) => <div key={index} className="h-14 animate-pulse rounded bg-raised/60" />)}</div> : list.rows.length === 0 ? (
            <EmptyState icon={<Bell className="h-5 w-5" />} title="No notifications" description="Alerts generated by correlation and scanning will appear here." />
          ) : (
            <div className="divide-y divide-border/50">
              {list.rows.map((notification) => (
                <button
                  key={notification.id}
                  onClick={async () => { await notificationApi.markRead(notification.id); list.refetch(); }}
                  className={`block w-full px-4 py-3 text-left hover:bg-raised/50 ${!notification.read_at ? "bg-accent/[0.04]" : ""}`}
                >
                  <div className="flex items-center justify-between gap-2">
                    <div className="flex items-center gap-2">
                      <SeverityBadge severity={notification.severity} />
                      <Badge>{notification.event_key}</Badge>
                      <Badge tone={notification.status === "sent" ? "border-accent/30 bg-accent/10 text-accent" : undefined}>{notification.status}</Badge>
                    </div>
                    <span className="text-2xs text-muted">{relativeTime(notification.created_at)}</span>
                  </div>
                  <p className="mt-1.5 text-sm font-medium text-ink">{notification.subject}</p>
                  <p className="mt-0.5 text-xs text-muted">{notification.body}</p>
                  <p className="mt-1 text-[10px] text-muted/70">Channel: {notification.channel} · {notification.read_at ? "read" : "unread"}</p>
                </button>
              ))}
            </div>
          )}
          {list.pagination ? <Pagination page={list.page} pages={list.pagination.pages} total={list.pagination.total} pageSize={list.pageSize} onPage={list.setPage} onPageSize={list.setPageSize} /> : null}
        </Card>

        <div className="space-y-4">
          <Card>
            <CardHeader title="Routing rules" description="Severity gates and dedup windows" action={can("notifications:write") ? <Button variant="outline" size="sm" onClick={() => setRuleOpen(true)}>New rule</Button> : undefined} />
            {(rules.data?.items ?? []).length === 0 ? <EmptyState title="No rules" description="Default in-app notifications apply until a rule is created." className="py-8" /> : (
              <div className="divide-y divide-border/50">
                {(rules.data?.items ?? []).map((item: any) => (
                  <div key={item.id} className="px-3.5 py-2.5">
                    <div className="flex items-center justify-between">
                      <p className="text-xs font-medium text-ink">{item.name}</p>
                      {can("notifications:write") ? (
                        <Switch checked={item.enabled} onChange={async (value) => { await notificationApi.updateRule(item.id, { enabled: value }); rules.refetch(); }} />
                      ) : <Badge>{item.enabled ? "enabled" : "disabled"}</Badge>}
                    </div>
                    <p className="mono text-[10px] text-muted">{item.event_key} · ≥ {item.min_severity} · {item.channels.join(", ")}</p>
                    <p className="text-[10px] text-muted">Dedup window {item.dedup_window_minutes}m</p>
                  </div>
                ))}
              </div>
            )}
          </Card>
          <Card>
            <CardHeader title="Delivery channels" description="External delivery requires configuration" />
            <div className="space-y-2 p-3.5 text-2xs">
              {["in_app", "email", "slack", "teams", "webhook"].map((channel) => (
                <div key={channel} className="flex items-center justify-between">
                  <span className="text-muted">{titleCase(channel)}</span>
                  <Badge tone={channel === "in_app" ? "border-accent/30 bg-accent/10 text-accent" : undefined}>{channel === "in_app" ? "active" : "provider required"}</Badge>
                </div>
              ))}
            </div>
          </Card>
        </div>
      </div>

      <Modal
        open={ruleOpen}
        onClose={() => setRuleOpen(false)}
        title="New notification rule"
        footer={<><Button variant="ghost" onClick={() => setRuleOpen(false)}>Cancel</Button><Button variant="primary" loading={createRule.isPending} disabled={!rule.name} onClick={() => createRule.mutate()}>Create rule</Button></>}
      >
        <div className="grid grid-cols-2 gap-3">
          <Field label="Name" className="col-span-2"><Input value={rule.name} onChange={(event) => setRule({ ...rule, name: event.target.value })} /></Field>
          <Field label="Event">
            <Select value={rule.event_key} onChange={(event) => setRule({ ...rule, event_key: event.target.value })}>
              {EVENTS.map((value) => <option key={value} value={value}>{value}</option>)}
            </Select>
          </Field>
          <Field label="Minimum severity">
            <Select value={rule.min_severity} onChange={(event) => setRule({ ...rule, min_severity: event.target.value })}>
              {["critical", "high", "medium", "low", "info"].map((value) => <option key={value} value={value}>{titleCase(value)}</option>)}
            </Select>
          </Field>
          <Field label="Channels" hint="Comma separated: in_app, email, slack, teams, webhook" className="col-span-2">
            <Input value={rule.channels} onChange={(event) => setRule({ ...rule, channels: event.target.value })} />
          </Field>
          <Field label="Dedup window (minutes)"><Input type="number" min={1} max={1440} value={rule.dedup_window_minutes} onChange={(event) => setRule({ ...rule, dedup_window_minutes: Number(event.target.value) })} /></Field>
        </div>
      </Modal>
    </div>
  );
}
